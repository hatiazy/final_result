def run(spot_path: str | Path, holding_path: str | Path, output_dir: str | Path, panel_path: str | Path | None = None) -> dict[str, Any]:
    spot_path = Path(spot_path).expanduser().resolve()
    holding_path = Path(holding_path).expanduser().resolve()
    output_dir = Path(output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    panel = Path(panel_path).expanduser().resolve() if panel_path else None

    frame = build_execution_frame(spot_path, holding_path)
    segments = build_segments(frame)
    annual = build_annual_tables(frame)
    risk = build_risk_summary(frame)
    valid = frame.loc[frame["O2O可评价"]].copy()

    frame.to_csv(output_dir / "O2O加算逐日收益与状态.csv", index=False, encoding="utf-8-sig", date_format="%Y-%m-%d")
    segments.to_csv(output_dir / "原始与调整_持有段明细.csv", index=False, encoding="utf-8-sig", date_format="%Y-%m-%d")
