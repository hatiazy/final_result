def _segment_tables(segments: pd.DataFrame, series: str) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    directional = segments.loc[(segments["series"] == series) & segments["is_directional"] & segments["return_available"]].copy()
    rows: list[dict[str, Any]] = []
    win_rows: list[dict[str, Any]] = []
    length_rows: list[dict[str, Any]] = []
    for year, group in directional.groupby("year", sort=True):
        short = group.loc[group["state"] == -1, "segment_return"] * 100.0
        long = group.loc[group["state"] == 1, "segment_return"] * 100.0
        row = {"Year": int(year), "Split": f"[{_phase(int(year))}]"}
        for prefix, values in (("Short", short), ("Long", long)):
            row[f"{prefix}_N"] = int(len(values))
            row[f"{prefix}_Mean"] = float(values.mean()) if len(values) else np.nan
            row[f"{prefix}_Med"] = float(values.median()) if len(values) else np.nan
            row[f"{prefix}_Max"] = float(values.max()) if len(values) else np.nan
            row[f"{prefix}_Min"] = float(values.min()) if len(values) else np.nan
        rows.append(row)
        all_values = pd.concat([short, long], ignore_index=True)
        win_rows.append({
            "Year": int(year),
            "Split": f"[{_phase(int(year))}]",
            "Short": int(len(short)),
            "Short_Win": int((short > 0).sum()),
            "Short_WinPct": float((short > 0).mean() * 100.0) if len(short) else np.nan,
            "Long": int(len(long)),
            "Long_Win": int((long > 0).sum()),
            "Long_WinPct": float((long > 0).mean() * 100.0) if len(long) else np.nan,
            "All": int(len(all_values)),
            "All_Win": int((all_values > 0).sum()),
            "All_WinPct": float((all_values > 0).mean() * 100.0) if len(all_values) else np.nan,
            "All_ReturnPct": float(all_values.sum()) if len(all_values) else np.nan,
        })
    all_segments = segments.loc[(segments["series"] == series) & segments["is_directional"]].copy()
    for year, group in all_segments.groupby("year", sort=True):
        length_rows.append({
            "Year": int(year),
            "Split": f"[{_phase(int(year))}]",
            "Short_Count": int((group["state"] == -1).sum()),
            "Short_MeanDays": float(group.loc[group["state"] == -1, "holding_days"].mean()) if (group["state"] == -1).any() else np.nan,
            "Long_Count": int((group["state"] == 1).sum()),
            "Long_MeanDays": float(group.loc[group["state"] == 1, "holding_days"].mean()) if (group["state"] == 1).any() else np.nan,
            "All_Count": int(len(group)),
            "All_MeanDays": float(group["holding_days"].mean()) if len(group) else np.nan,
        })
    return pd.DataFrame(rows), pd.DataFrame(win_rows), pd.DataFrame(length_rows)


