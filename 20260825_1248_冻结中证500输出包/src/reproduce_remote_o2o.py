    annual["adjusted"].to_csv(output_dir / "加入四个反转_年度分析.csv", index=False, encoding="utf-8-sig")
    annual["signals"].to_csv(output_dir / "年度信号计数.csv", index=False, encoding="utf-8-sig")
    risk.to_csv(output_dir / "O2O加算风险指标.csv", index=False, encoding="utf-8-sig")

    _plot_segment_tables(segments, output_dir, "Raw 1545", "01_原始三状态")
    _plot_segment_tables(segments, output_dir, "Adj 1545", "05_加入四个反转")
    _plot_annual_state_summary(frame, annual["raw"], output_dir / "09_原始三状态_年度收益状态分布与信号计数.png", adjusted=False)
    _plot_annual_state_summary(frame, annual["adjusted"], output_dir / "10_加入四个反转_年度收益状态分布与信号计数.png", adjusted=True)
    _plot_bar_table(risk, output_dir / "11_原始与调整_风险指标对比.png")
    _plot_nav(
        frame,
        output_dir / "12_原始与调整_净值对比.png",
        [("原始净值", "Raw 1545 NAV", "#f58518"), ("调整净值", "Adjusted 1545 NAV", "#d62728"), ("指数净值", "Index B&H NAV", "#4285f4")],
        "1545 三状态：原始、调整与指数买入持有（净值）",
    )
    _plot_nav(
        frame,
        output_dir / "13_原始与调整_超额净值对比.png",
        [("原始超额净值", "Raw 1545 Excess NAV", "#f58518"), ("调整超额净值", "Adjusted 1545 Excess NAV", "#d62728")],
        "1545 原始与调整：相对中证500的超额净值",
    )
    _plot_nav(
        frame,
        output_dir / "14_调整相对原始_超额收益.png",
        [("调整相对原始净值", "Adjusted minus Raw (additive)", "#2ca02c")],
        "调整后1545相对原始状态的增量（加算）",
        ylabel="Relative NAV",
    )

    engine_panel = _load_engine_panel(spot_path, panel)
    internal = _plot_internal_diagnostics(engine_panel, frame, output_dir)

