def _load_engine_panel(spot_path: Path, panel_path: Path | None) -> pd.DataFrame | None:
    """Rebuild the sealed 1545 feature panel when the package code is usable."""

    if panel_path is not None and panel_path.is_file():
        try:
            panel = _read_table(panel_path)
            date_column = next((c for c in panel.columns if str(c).lower() in {"date", "formation_date"}), None)
            if date_column is not None and any(name in panel.columns for name in ("rule_axis", "cv_trend", "slow_engine", "fast_engine")):
                panel["date"] = _parse_dates(panel[date_column])
                return panel.dropna(subset=["date"]).sort_values("date").drop_duplicates("date")
        except Exception:
            pass
    try:
        package_root = next(
            parent for parent in [Path(__file__).resolve().parents[1], *Path(__file__).resolve().parents[1].parents]
            if (parent / "packages" / "nonzero" / "1545" / "src" / "common" / "data.py").is_file()
        )
        source_root = package_root / "packages" / "nonzero" / "1545" / "src"
        import importlib
        import inspect
        import sys

        # 04 may be run after 01 in the same Jupyter kernel.  The earlier
        # notebook can leave a different package's ``common`` module in
        # sys.modules, which would silently rebuild 1545 from the wrong
        # source.  Remove only this package namespace before importing the
        # sealed 1545 builder, then verify the imported file is from this
        # upload package.
        for module_name in list(sys.modules):
            if module_name == "common" or module_name.startswith("common."):
                del sys.modules[module_name]
        if str(source_root) in sys.path:
            sys.path.remove(str(source_root))
        sys.path.insert(0, str(source_root))
        importlib.invalidate_caches()
        os.environ["1545_SPOT_PATH"] = str(spot_path)
        from common.data import build_panel

        imported_from = Path(inspect.getfile(build_panel)).resolve()
        if source_root.resolve() not in imported_from.parents:
            raise RuntimeError(f"1545 builder 来源错误：{imported_from}")

        panel, _ = build_panel()
        panel = panel.reset_index(names="date")
        return panel
    except Exception:
        return None


