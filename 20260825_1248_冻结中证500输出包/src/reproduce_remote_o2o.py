"""Reproduce the remote 1545 analysis from the local frozen eight-list.

The production signal columns are generated by Notebook 03.  This module is
the analysis engine called by Notebooks 04 and 05.  It deliberately separates three
things that are easy to mix up:

* the signal row is an execution date, not the formation date;
* the performance return is execution-day open to the next actual trading
  day's open (O2O), not close to close;
* the curves use the research additive convention ``1 + cumsum(return)`` and
  never compound daily returns.

The last signal row is retained in the daily audit even when the next open is
not in the local file yet.  It is excluded from return curves and metrics until
that next price exists; it is not filled with zero and it is not treated as a
placeholder signal.
"""

