def build_fragmentation_diagnostics(segments: pd.DataFrame, short_segments: pd.DataFrame) -> dict[str, Any]:
    """Summarize how much fragmentation is structural versus short zero blips."""

    final = segments.loc[segments["series"].eq("Adj 1545")].copy().reset_index(drop=True)
    short = short_segments.copy()
    zero_blips = short.loc[
        short["state"].eq(0)
        & short["previous_state"].isin([-1, 1])
        & short["next_state"].eq(short["previous_state"])
    ]
    return {
        "series": "Adj 1545",
        "all_segments": int(len(final)),
        "one_day_segments": int((final["holding_days"] == 1).sum()),
        "two_day_segments": int((final["holding_days"] == 2).sum()),
        "one_or_two_day_segments": int(final["holding_days"].le(2).sum()),
        "one_or_two_day_pct": float(final["holding_days"].le(2).mean() * 100.0),
        "directional_short_segments": int(short["state"].isin([-1, 1]).sum()),
        "flat_short_segments": int(short["state"].eq(0).sum()),
        "same_direction_flat_blips_1_or_2_days": int(len(zero_blips)),
        "same_direction_flat_blips_by_days": {
            str(days): int((zero_blips["holding_days"] == days).sum()) for days in (1, 2)
        },
        "interpretation": (
            "一日/两日段由退出事件、0转持有路径被基础状态切断、同日上下冲突置0和基础状态短段共同形成；"
            "不能在不改变冻结状态定义的情况下直接全部合并。"
        ),
    }


def _annual_rows(frame: pd.DataFrame, state_column: str, return_column: str, name: str) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    work = frame.loc[frame["O2O可评价"]].copy()
    for year, group in work.groupby(work["实际执行日"].dt.year, sort=True):
        strategy = group[return_column].astype(float)
        market = group["指数日收益"].astype(float)
        states = group[state_column].astype(int)
        rows.append({
            "series": name,
            "year": int(year),
            "phase": _phase(int(year)),
            "strategy_return_pct": float(strategy.sum() * 100.0),
            "index_return_pct": float(market.sum() * 100.0),
            "excess_return_pct": float((strategy - market).sum() * 100.0),
            "short_days": int((states == -1).sum()),
            "flat_days": int((states == 0).sum()),
            "long_days": int((states == 1).sum()),
            "directional_days": int(states.ne(0).sum()),
            "winning_directional_days": int(strategy.loc[states.ne(0)].gt(0).sum()),
            "directional_win_rate_pct": float(strategy.loc[states.ne(0)].gt(0).mean() * 100.0) if states.ne(0).any() else np.nan,
            "mean_directional_return_pct": float(strategy.loc[states.ne(0)].mean() * 100.0) if states.ne(0).any() else np.nan,
            "days": int(len(group)),
        })
    return pd.DataFrame(rows)


def build_annual_tables(frame: pd.DataFrame) -> dict[str, pd.DataFrame]:
    raw = _annual_rows(frame, "原始状态", "原始策略日收益", "Raw 1545")
    adj = _annual_rows(frame, "调整后三状态", "调整策略日收益", "Adj 1545")
    signals = frame.groupby(frame["实际执行日"].dt.year).agg(
        zero_down_days=("0转-1", "sum"),
        zero_up_days=("0转+1", "sum"),
        plus_exit_days=("+1反转", "sum"),
        minus_exit_days=("-1反转", "sum"),
        big_up_days=("大涨", "sum"),
        big_down_days=("大跌", "sum"),
    ).reset_index(names="year")
    raw = raw.merge(signals, on="year", how="left")
    adj = adj.merge(signals, on="year", how="left")
    return {"raw": raw, "adjusted": adj, "signals": signals}


def build_risk_summary(frame: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    valid = frame.loc[frame["O2O可评价"]].copy()
    for name, return_column, state_column in (
        ("Raw 1545", "原始策略日收益", "原始状态"),
        ("Adj 1545 (+4 Reversal)", "调整策略日收益", "调整后三状态"),
        ("CSI500 Buy & Hold", "指数日收益", None),
    ):
        returns = valid[return_column].astype(float)
        nav = 1.0 + returns.cumsum()
        running_max = nav.cummax()
        drawdown = nav.div(running_max).sub(1.0)
        active = valid[state_column].ne(0) if state_column else pd.Series(True, index=valid.index)
        directional = returns.loc[active]
        mean_return = float(returns.mean())
        vol = float(returns.std(ddof=1) * np.sqrt(252)) if len(returns) > 1 else np.nan
        rows.append({
            "series": name,
            "start_date": valid["实际执行日"].iloc[0].strftime("%Y-%m-%d"),
            "end_date": valid["实际执行日"].iloc[-1].strftime("%Y-%m-%d"),
            "observations": int(len(valid)),
            "final_nav": float(nav.iloc[-1]),
            "total_return_pct": float((nav.iloc[-1] - 1.0) * 100.0),
            "annualized_additive_return_pct": mean_return * 252.0 * 100.0,
            "annualized_volatility_pct": vol * 100.0,
            "sharpe": float(mean_return * 252.0 / vol) if np.isfinite(vol) and vol > 0 else np.nan,
            "max_drawdown_pct": float(drawdown.min() * 100.0),
            "active_days": int(active.sum()),
            "winning_directional_days": int(directional.gt(0).sum()),
            "directional_win_rate_pct": float(directional.gt(0).mean() * 100.0) if len(directional) else np.nan,
            "daily_win_rate_pct": float(returns.gt(0).mean() * 100.0),
        })
    return pd.DataFrame(rows)


def _save_table_figure(text: str, path: Path, *, title: str | None = None, dark: bool = True) -> None:
    lines = text.splitlines() or [""]
    height = max(3.0, min(12.0, 0.34 * len(lines) + 0.9))
    fig = plt.figure(figsize=(12.0, height), dpi=150)
    if dark:
        fig.patch.set_facecolor("#101010")
        color = "#f0f0f0"
    else:
        fig.patch.set_facecolor("white")
        color = "#111111"
    if title:
        fig.text(0.5, 0.98, title, ha="center", va="top", color=color, fontsize=13, weight="bold")
        y = 0.93
    else:
        y = 0.97
    fig.text(0.025, y, text, ha="left", va="top", color=color, family="monospace", fontsize=8.5)
    fig.savefig(path, dpi=150, bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.close(fig)


def _fmt_table(frame: pd.DataFrame, columns: list[str] | None = None, percent_columns: tuple[str, ...] = ()) -> str:
    if frame.empty:
        return "(empty)"
    view = frame.copy()
    if columns is not None:
        view = view.loc[:, [c for c in columns if c in view.columns]]
    for column in percent_columns:
        if column in view.columns:
            view[column] = view[column].map(lambda x: "nan" if pd.isna(x) else f"{float(x):+.2f}%")
    return view.to_string(index=False)


