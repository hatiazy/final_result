def _plot_annual_state_summary(frame: pd.DataFrame, annual: pd.DataFrame, output: Path, adjusted: bool) -> None:
    state_column = "调整后三状态" if adjusted else "原始状态"
    return_column = "调整策略日收益" if adjusted else "原始策略日收益"
    title_prefix = "加入四个反转" if adjusted else "原始三状态"
    rows: list[str] = [f"{title_prefix} — Annual Breakdown: PnL + State Distribution + Signal Counts", ""]
    table = annual.copy()
    table["Ret%"] = table["strategy_return_pct"].map(lambda x: f"{x:+.2f}%")
    table["Idx%"] = table["index_return_pct"].map(lambda x: f"{x:+.2f}%")
    table["Ex%"] = table["excess_return_pct"].map(lambda x: f"{x:+.2f}%")
    table["Short"] = table["short_days"].astype(int)
    table["Flat"] = table["flat_days"].astype(int)
    table["Long"] = table["long_days"].astype(int)
    table["0→-1"] = table["zero_down_days"].astype(int)
    table["0→+1"] = table["zero_up_days"].astype(int)
    table["Days"] = table["days"].astype(int)
    rows.append(_fmt_table(table[["year", "Ret%", "Idx%", "Ex%", "Short", "Flat", "Long", "0→-1", "0→+1", "Days"]]))
    rows.append("")
    rows.append("State distribution (%):")
    for _, row in table.iterrows():
        year = int(row["year"])
        g = frame.loc[frame["实际执行日"].dt.year.eq(year)]
        counts = g[state_column].value_counts()
        total = max(len(g), 1)
        rows.append(
            f"  {year}: Short= {int(counts.get(-1, 0))} ({counts.get(-1, 0) / total * 100:.1f}%), "
            f"Flat= {int(counts.get(0, 0))} ({counts.get(0, 0) / total * 100:.1f}%), "
            f"Long= {int(counts.get(1, 0))} ({counts.get(1, 0) / total * 100:.1f}%)"
        )
    _save_table_figure("\n".join(rows), output, dark=True)


