SIGNAL_COLUMNS = [
    "实际执行日",
    "三状态",
    "+1反转",
    "-1反转",
    "0转-1",
    "0转+1",
    "大涨",
    "大跌",
]


def _parse_dates(values: pd.Series) -> pd.Series:
    text = values.astype("string").str.strip().str.replace(r"\.0+$", "", regex=True)
    compact = text.str.fullmatch(r"\d{8}", na=False)
    result = pd.Series(pd.NaT, index=values.index, dtype="datetime64[ns]")
    if (~compact).any():
        result.loc[~compact] = pd.to_datetime(
            text.loc[~compact], errors="coerce", format="mixed"
        )
    if compact.any():
        result.loc[compact] = pd.to_datetime(
            text.loc[compact], errors="coerce", format="%Y%m%d"
        )
    return result.dt.normalize()


def _read_table(path: Path) -> pd.DataFrame:
    if not path.is_absolute():
        raise ValueError(f"路径必须是绝对路径：{path}")
    if path.suffix.lower() == ".parquet":
        frame = pd.read_parquet(path)
    elif path.suffix.lower() in {".csv", ".tsv"}:
        frame = pd.read_csv(path, sep="\t" if path.suffix.lower() == ".tsv" else ",", encoding="utf-8-sig")
    else:
        raise ValueError(f"不支持的表格格式：{path}")
    if isinstance(frame.index, pd.DatetimeIndex):
        frame = frame.reset_index()
    return frame


def read_spot(path: str | Path) -> pd.DataFrame:
    """Load only local spot OHLC data and build the actual trading calendar."""

    path = Path(path).expanduser().resolve()
    if not path.is_file():
        raise FileNotFoundError(f"本地现货不存在：{path}")
    raw = _read_table(path)
    lower = {str(column).strip().lower(): column for column in raw.columns}

    def choose(names: tuple[str, ...], label: str) -> Any:
        for name in names:
            if name.lower() in lower:
                return lower[name.lower()]
        raise ValueError(f"现货缺少 {label} 字段；实际字段={list(raw.columns)}")

    date_column = choose(("date", "trade_dt", "trade_date", "交易日", "datetime"), "交易日")
    open_column = choose(("open", "开盘", "open_price"), "open")
    close_column = next((lower[x] for x in ("close", "收盘", "close_price") if x in lower), None)
    high_column = next((lower[x] for x in ("high", "最高", "highestprice") if x in lower), None)
    low_column = next((lower[x] for x in ("low", "最低", "lowestprice") if x in lower), None)

    result = pd.DataFrame({
        "date": _parse_dates(raw[date_column]),
        "open": pd.to_numeric(raw[open_column], errors="coerce"),
    })
    for target, source in (("close", close_column), ("high", high_column), ("low", low_column)):
        result[target] = (
            pd.to_numeric(raw[source], errors="coerce") if source is not None else np.nan
        )
    result = result.dropna(subset=["date", "open"])
    result = result.loc[result["open"] > 0]
    result = result.sort_values("date", kind="stable").drop_duplicates("date", keep="last")
    result = result.reset_index(drop=True)
    if len(result) < 2:
        raise ValueError("现货至少需要两个实际交易日才能计算 O2O")
    return result


def read_holding_eight(path: str | Path) -> pd.DataFrame:
    path = Path(path).expanduser().resolve()
    if not path.is_file():
        raise FileNotFoundError(f"04 的含持有期八列表不存在：{path}")
    frame = _read_table(path)
    if list(frame.columns) != SIGNAL_COLUMNS:
        raise ValueError(
            "04 输出列顺序不符合冻结包约定："
            f"实际={list(frame.columns)}，期望={SIGNAL_COLUMNS}"
        )
    frame = frame.loc[:, SIGNAL_COLUMNS].copy()
    frame["实际执行日"] = _parse_dates(frame["实际执行日"])
    if frame["实际执行日"].isna().any():
        raise ValueError("04 八列表存在无法解析的实际执行日")
    if frame["实际执行日"].duplicated().any():
        raise ValueError("04 八列表存在重复实际执行日")
    if not frame["实际执行日"].is_monotonic_increasing:
        raise ValueError("04 八列表实际执行日未排序")
    for column in SIGNAL_COLUMNS[1:]:
        frame[column] = pd.to_numeric(frame[column], errors="raise").astype("int8")
    if not frame[SIGNAL_COLUMNS[2:]].isin([0, 1]).all().all():
        raise ValueError("04 八列表包含非 0/1 信号值")
    if not frame["三状态"].isin([-1, 0, 1]).all():
        raise ValueError("04 八列表包含非法三状态")
    return frame


def _phase(year: int) -> str:
    if year <= 2022:
        return "Train"
    if year <= 2024:
        return "Val"
    return "Test"


def build_adjusted_state(frame: pd.DataFrame) -> pd.DataFrame:
    """Apply the remote Raw/Adj state rule to the holding-aware eight-list.

    `0转-1` and `0转+1` are already continuous holding-path columns in the
    04 output.  They are used only while the base state is 0.  The two exit
    columns are event-day exits: -1/+1 becomes 0 on that row, and later rows
    continue to follow the base state.  Same-day zero-direction conflict is
    neutralized.
    """

    result = frame.copy()
    base = result["三状态"].to_numpy(dtype=int)
    plus_exit = result["+1反转"].to_numpy(dtype=bool)
    minus_exit = result["-1反转"].to_numpy(dtype=bool)
    down = result["0转-1"].to_numpy(dtype=bool)
    up = result["0转+1"].to_numpy(dtype=bool)
    adjusted = np.zeros(len(result), dtype=np.int8)
    reasons: list[str] = []

    for i, state in enumerate(base):
        if state == -1:
            adjusted[i] = 0 if minus_exit[i] else -1
            reasons.append("-1退出到0" if minus_exit[i] else "基础-1")
        elif state == 1:
            adjusted[i] = 0 if plus_exit[i] else 1
            reasons.append("+1退出到0" if plus_exit[i] else "基础+1")
        elif state == 0:
            if down[i] and up[i]:
                adjusted[i] = 0
                reasons.append("零段同日冲突置0")
            elif down[i]:
                adjusted[i] = -1
                reasons.append("0转-1持有")
            elif up[i]:
                adjusted[i] = 1
                reasons.append("0转+1持有")
            else:
                adjusted[i] = 0
                reasons.append("基础0")
        else:
            raise ValueError(f"非法三状态：{state}")

    result["调整后三状态"] = adjusted
    result["调整原因"] = reasons
    result["阶段"] = result["实际执行日"].dt.year.map(_phase)
    return result


def build_execution_frame(spot_path: str | Path, holding_path: str | Path) -> pd.DataFrame:
    """Join 04 signals to spot prices and calculate execution-date O2O."""

    spot = read_spot(spot_path)
    signal = build_adjusted_state(read_holding_eight(holding_path))
    price = spot.copy()
    price["下一实际交易日"] = price["date"].shift(-1)
    price["下一交易日开盘"] = price["open"].shift(-1)
    price["执行日O2O"] = price["下一交易日开盘"].div(price["open"]).sub(1.0)
    price["行情中有执行日价格"] = True
    price = price.rename(columns={"date": "实际执行日", "open": "执行日开盘"})
    frame = signal.merge(price, on="实际执行日", how="left", validate="one_to_one")

    calendar = pd.DatetimeIndex(spot["date"])
    previous_map = pd.Series(calendar[:-1].to_numpy(), index=calendar[1:])
    frame["推定形成日"] = frame["实际执行日"].map(previous_map)
    pending = frame["推定形成日"].isna() & frame["实际执行日"].gt(calendar[-1])
    frame.loc[pending, "推定形成日"] = calendar[-1]
    frame["形成日早于执行日"] = frame["推定形成日"].notna() & frame["推定形成日"].lt(frame["实际执行日"])
    if not frame["形成日早于执行日"].all():
        bad = frame.loc[~frame["形成日早于执行日"], ["实际执行日", "推定形成日"]]
        raise AssertionError(f"存在形成日不早于执行日的行：{bad.head().to_dict('records')}")

    frame["原始状态"] = frame["三状态"].astype("int8")
    frame["原始策略日收益"] = frame["原始状态"].astype(float) * frame["执行日O2O"]
    frame["调整策略日收益"] = frame["调整后三状态"].astype(float) * frame["执行日O2O"]
    frame["指数日收益"] = frame["执行日O2O"]
    frame["O2O可评价"] = frame["执行日O2O"].notna()
    frame["原始净值"] = np.nan
    frame["调整净值"] = np.nan
    frame["指数净值"] = np.nan
    valid = frame["O2O可评价"]
    frame.loc[valid, "原始净值"] = 1.0 + frame.loc[valid, "原始策略日收益"].cumsum()
    frame.loc[valid, "调整净值"] = 1.0 + frame.loc[valid, "调整策略日收益"].cumsum()
    frame.loc[valid, "指数净值"] = 1.0 + frame.loc[valid, "指数日收益"].cumsum()
    frame["原始超额净值"] = np.nan
    frame["调整超额净值"] = np.nan
    frame["调整相对原始净值"] = np.nan
    frame.loc[valid, "原始超额净值"] = 1.0 + (
        frame.loc[valid, "原始策略日收益"] - frame.loc[valid, "指数日收益"]
    ).cumsum()
    frame.loc[valid, "调整超额净值"] = 1.0 + (
        frame.loc[valid, "调整策略日收益"] - frame.loc[valid, "指数日收益"]
    ).cumsum()
    frame.loc[valid, "调整相对原始净值"] = 1.0 + (
        frame.loc[valid, "调整策略日收益"] - frame.loc[valid, "原始策略日收益"]
    ).cumsum()
    return frame


def _directional_segments(frame: pd.DataFrame, state_column: str, return_column: str, series: str) -> pd.DataFrame:
    work = frame[["实际执行日", state_column, return_column, "阶段"]].copy()
    work["run_id"] = work[state_column].ne(work[state_column].shift()).cumsum()
    rows: list[dict[str, Any]] = []
    for run_id, group in work.groupby("run_id", sort=True):
        state = int(group[state_column].iloc[0])
        returns = pd.to_numeric(group[return_column], errors="coerce")
        rows.append({
            "series": series,
            "run_id": int(run_id),
            "state": state,
            "start_date": group["实际执行日"].iloc[0],
            "end_date": group["实际执行日"].iloc[-1],
            "year": int(group["实际执行日"].iloc[0].year),
            "phase": str(group["阶段"].iloc[0]),
            "holding_days": int(len(group)),
            "segment_return": float(returns.sum()) if returns.notna().any() else np.nan,
            "return_available": bool(returns.notna().all()),
        })
    return pd.DataFrame(rows)


def build_segments(frame: pd.DataFrame) -> pd.DataFrame:
    parts = [
        _directional_segments(frame, "原始状态", "原始策略日收益", "Raw 1545"),
        _directional_segments(frame, "调整后三状态", "调整策略日收益", "Adj 1545"),
    ]
    result = pd.concat(parts, ignore_index=True)
    result["aligned_segment_return"] = result["segment_return"]
    result["is_directional"] = result["state"].isin([-1, 1])
    return result


def _annual_rows(frame: pd.DataFrame, state_column: str, return_column: str, name: str) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    work = frame.loc[frame["O2O可评价"]].copy()
    for year, group in work.groupby(work["实际执行日"].dt.year, sort=True):
        strategy = group[return_column].astype(float)
        market = group["指数日收益"].astype(float)
        states = group[state_column].astype(int)
        rows.append({
            "series": name,
            "year": int(year),
            "phase": _phase(int(year)),
            "strategy_return_pct": float(strategy.sum() * 100.0),
            "index_return_pct": float(market.sum() * 100.0),
            "excess_return_pct": float((strategy - market).sum() * 100.0),
            "short_days": int((states == -1).sum()),
            "flat_days": int((states == 0).sum()),
            "long_days": int((states == 1).sum()),
            "directional_days": int(states.ne(0).sum()),
            "winning_directional_days": int(strategy.loc[states.ne(0)].gt(0).sum()),
            "directional_win_rate_pct": float(strategy.loc[states.ne(0)].gt(0).mean() * 100.0) if states.ne(0).any() else np.nan,
            "mean_directional_return_pct": float(strategy.loc[states.ne(0)].mean() * 100.0) if states.ne(0).any() else np.nan,
            "days": int(len(group)),
        })
    return pd.DataFrame(rows)


def build_annual_tables(frame: pd.DataFrame) -> dict[str, pd.DataFrame]:
    raw = _annual_rows(frame, "原始状态", "原始策略日收益", "Raw 1545")
    adj = _annual_rows(frame, "调整后三状态", "调整策略日收益", "Adj 1545")
    signals = frame.groupby(frame["实际执行日"].dt.year).agg(
        zero_down_days=("0转-1", "sum"),
        zero_up_days=("0转+1", "sum"),
        plus_exit_days=("+1反转", "sum"),
        minus_exit_days=("-1反转", "sum"),
        big_up_days=("大涨", "sum"),
        big_down_days=("大跌", "sum"),
    ).reset_index(names="year")
    raw = raw.merge(signals, on="year", how="left")
    adj = adj.merge(signals, on="year", how="left")
    return {"raw": raw, "adjusted": adj, "signals": signals}


def build_risk_summary(frame: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    valid = frame.loc[frame["O2O可评价"]].copy()
    for name, return_column, state_column in (
        ("Raw 1545", "原始策略日收益", "原始状态"),
        ("Adj 1545 (+4 Reversal)", "调整策略日收益", "调整后三状态"),
        ("CSI500 Buy & Hold", "指数日收益", None),
    ):
        returns = valid[return_column].astype(float)
        nav = 1.0 + returns.cumsum()
        running_max = nav.cummax()
        drawdown = nav.div(running_max).sub(1.0)
        active = valid[state_column].ne(0) if state_column else pd.Series(True, index=valid.index)
        directional = returns.loc[active]
        mean_return = float(returns.mean())
        vol = float(returns.std(ddof=1) * np.sqrt(252)) if len(returns) > 1 else np.nan
        rows.append({
            "series": name,
            "start_date": valid["实际执行日"].iloc[0].strftime("%Y-%m-%d"),
            "end_date": valid["实际执行日"].iloc[-1].strftime("%Y-%m-%d"),
            "observations": int(len(valid)),
            "final_nav": float(nav.iloc[-1]),
            "total_return_pct": float((nav.iloc[-1] - 1.0) * 100.0),
            "annualized_additive_return_pct": mean_return * 252.0 * 100.0,
            "annualized_volatility_pct": vol * 100.0,
            "sharpe": float(mean_return * 252.0 / vol) if np.isfinite(vol) and vol > 0 else np.nan,
            "max_drawdown_pct": float(drawdown.min() * 100.0),
            "active_days": int(active.sum()),
            "winning_directional_days": int(directional.gt(0).sum()),
            "directional_win_rate_pct": float(directional.gt(0).mean() * 100.0) if len(directional) else np.nan,
            "daily_win_rate_pct": float(returns.gt(0).mean() * 100.0),
        })
    return pd.DataFrame(rows)


def _save_table_figure(text: str, path: Path, *, title: str | None = None, dark: bool = True) -> None:
    lines = text.splitlines() or [""]
    height = max(3.0, min(12.0, 0.34 * len(lines) + 0.9))
    fig = plt.figure(figsize=(12.0, height), dpi=150)
    if dark:
        fig.patch.set_facecolor("#101010")
        color = "#f0f0f0"
    else:
        fig.patch.set_facecolor("white")
        color = "#111111"
    if title:
        fig.text(0.5, 0.98, title, ha="center", va="top", color=color, fontsize=13, weight="bold")
        y = 0.93
    else:
        y = 0.97
    fig.text(0.025, y, text, ha="left", va="top", color=color, family="monospace", fontsize=8.5)
    fig.savefig(path, dpi=150, bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.close(fig)


def _fmt_table(frame: pd.DataFrame, columns: list[str] | None = None, percent_columns: tuple[str, ...] = ()) -> str:
    if frame.empty:
        return "(empty)"
    view = frame.copy()
    if columns is not None:
        view = view.loc[:, [c for c in columns if c in view.columns]]
    for column in percent_columns:
        if column in view.columns:
            view[column] = view[column].map(lambda x: "nan" if pd.isna(x) else f"{float(x):+.2f}%")
    return view.to_string(index=False)


def _plot_nav(frame: pd.DataFrame, output: Path, column_map: list[tuple[str, str, str]], title: str, ylabel: str = "NAV") -> None:
    valid = frame.loc[frame["O2O可评价"]].copy()
    fig, ax = plt.subplots(figsize=(13.2, 5.2), dpi=150)
    for column, label, color in column_map:
        ax.plot(valid["实际执行日"], valid[column], linewidth=1.15, label=label, color=color)
    ax.axhline(1.0, color="#666", linewidth=0.55, linestyle=":")
    ax.set_title(title, fontsize=13, weight="bold")
    ax.set_ylabel(ylabel)
    ax.set_xlabel("Date")
    ax.grid(True, alpha=0.35, linewidth=0.45)
    ax.xaxis.set_major_locator(mdates.YearLocator())
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))
    ax.legend(loc="upper left", fontsize=9)
    fig.tight_layout()
    fig.savefig(output, dpi=150, bbox_inches="tight", facecolor="white")
    plt.close(fig)


