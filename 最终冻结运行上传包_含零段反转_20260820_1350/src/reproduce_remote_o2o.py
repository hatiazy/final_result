def _attach_adjusted_to_engine(panel: pd.DataFrame, frame: pd.DataFrame) -> pd.DataFrame:
    work = panel.copy()
    if "date" not in work.columns:
        return work
    effective = work.get("effective_date")
    if effective is None:
        work["effective_date"] = work["date"].shift(-1)
        effective = work["effective_date"]
    work["effective_date"] = _parse_dates(pd.Series(effective, index=work.index))
    mapping = frame.set_index("实际执行日")["调整后三状态"]
    raw_mapping = frame.set_index("实际执行日")["原始状态"]
    work["adjusted_state"] = work["effective_date"].map(mapping)
    work["raw_state"] = work["effective_date"].map(raw_mapping)
    return work


