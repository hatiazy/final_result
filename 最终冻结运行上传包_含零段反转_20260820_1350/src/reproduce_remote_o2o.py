def _write_2026_analysis(frame: pd.DataFrame, output_dir: Path) -> dict[str, Any]:
    """Produce the explicit 2026 decomposition requested for Notebook 05."""

    work = frame.loc[frame["O2O可评价"]].copy()
    work["year"] = work["实际执行日"].dt.year
    work["month"] = work["实际执行日"].dt.to_period("M").astype(str)
    work_2026 = work.loc[work["year"] == 2026].copy()
    monthly = work_2026.groupby("month", sort=True).agg(
        days=("实际执行日", "size"),
        raw_return_pct=("原始策略日收益", lambda x: float(x.sum() * 100.0)),
        adjusted_return_pct=("调整策略日收益", lambda x: float(x.sum() * 100.0)),
        index_return_pct=("指数日收益", lambda x: float(x.sum() * 100.0)),
        raw_active_days=("原始状态", lambda x: int(x.ne(0).sum())),
        adjusted_active_days=("调整后三状态", lambda x: int(x.ne(0).sum())),
        adjusted_winning_days=("调整策略日收益", lambda x: int(x.gt(0).sum())),
    ).reset_index()
    monthly["adjusted_excess_pct"] = monthly["adjusted_return_pct"] - monthly["index_return_pct"]
    monthly.to_csv(output_dir / "2026_逐月表现分解.csv", index=False, encoding="utf-8-sig")

    year = work.loc[work["year"] == 2026].copy()
    if not year.empty:
        year["raw_nav_2026"] = 1.0 + year["原始策略日收益"].cumsum()
        year["adjusted_nav_2026"] = 1.0 + year["调整策略日收益"].cumsum()
        year["index_nav_2026"] = 1.0 + year["指数日收益"].cumsum()
        year["adjusted_excess_2026"] = 1.0 + (year["调整策略日收益"] - year["指数日收益"]).cumsum()
        year["adjusted_minus_raw_2026"] = 1.0 + (year["调整策略日收益"] - year["原始策略日收益"]).cumsum()
        year.to_csv(output_dir / "2026_逐日表现分解.csv", index=False, encoding="utf-8-sig", date_format="%Y-%m-%d")

        fig, axes = plt.subplots(3, 1, figsize=(12.5, 8.2), dpi=140, sharex=True, gridspec_kw={"height_ratios": [1.0, 1.0, 0.65]})
        axes[0].plot(year["实际执行日"], year["原始策略日收益"] * 100.0, color="#f58518", linewidth=0.8, label="Raw daily O2O return %")
        axes[0].plot(year["实际执行日"], year["调整策略日收益"] * 100.0, color="#d62728", linewidth=0.8, label="Adj daily O2O return %")
        axes[0].plot(year["实际执行日"], year["指数日收益"] * 100.0, color="#4285f4", linewidth=0.65, alpha=0.7, label="Index O2O return %")
        axes[0].axhline(0, color="#666", linewidth=0.55)
        axes[0].set_ylabel("Daily %")
        axes[0].legend(fontsize=8, loc="upper left")
        axes[1].plot(year["实际执行日"], year["raw_nav_2026"], color="#f58518", label="Raw NAV")
        axes[1].plot(year["实际执行日"], year["adjusted_nav_2026"], color="#d62728", label="Adj NAV")
        axes[1].plot(year["实际执行日"], year["index_nav_2026"], color="#4285f4", label="Index NAV")
        axes[1].plot(year["实际执行日"], year["adjusted_excess_2026"], color="#2ca02c", linestyle="--", label="Adj Excess NAV")
        axes[1].axhline(1.0, color="#666", linewidth=0.55, linestyle=":")
        axes[1].set_ylabel("2026 NAV")
        axes[1].legend(fontsize=8, loc="upper left")
        axes[2].set_ylim(-1.05, 1.05)
        axes[2].set_yticks([-1, 0, 1], labels=["Short", "Flat", "Long"])
        _state_background(axes[2], year["实际执行日"].reset_index(drop=True), year["调整后三状态"].reset_index(drop=True))
        axes[2].set_ylabel("Adj state")
        axes[2].xaxis.set_major_locator(mdates.MonthLocator())
        axes[2].xaxis.set_major_formatter(mdates.DateFormatter("%Y-%m"))
        fig.suptitle("2026 Performance Decomposition: O2O Additive Return and State Coverage", fontsize=13, weight="bold")
        fig.tight_layout()
        fig.savefig(output_dir / "2026_表现分解_收益与状态.png", dpi=140, bbox_inches="tight", facecolor="white")
        plt.close(fig)

    return {
        "rows_2026": int(len(year)),
        "months_2026": int(len(monthly.loc[monthly["month"].str.startswith("2026")])) if not monthly.empty else 0,
        "total_adjusted_return_pct": float(year["调整策略日收益"].sum() * 100.0) if not year.empty else np.nan,
        "total_index_return_pct": float(year["指数日收益"].sum() * 100.0) if not year.empty else np.nan,
        "adjusted_active_days": int(year["调整后三状态"].ne(0).sum()) if not year.empty else 0,
    }


